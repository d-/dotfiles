function M.lualine()
  local p = M.palette
  local function mode(a)
    return {
      a = a,
      b = { fg = p.g2, bg = p.black },
      c = { fg = p.gray4, bg = p.black },
    }
  end
  return {
    normal = mode({ fg = p.g0, bg = p.black, gui = 'bold' }),
    insert = mode({ fg = p.black, bg = p.g0, gui = 'bold' }),
    visual = mode({ fg = p.black, bg = p.g2, gui = 'bold' }),
    replace = mode({ fg = p.black, bg = p.red, gui = 'bold' }),
    command = mode({ fg = p.g2, bg = p.black, gui = 'bold' }),
    terminal = mode({ fg = p.black, bg = p.g0, gui = 'bold' }),
    inactive = {
      a = { fg = p.gray2, bg = p.black },
      b = { fg = p.gray2, bg = p.black },
      c = { fg = p.gray2, bg = p.black },
    },
  }
end

