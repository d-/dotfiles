-- duogreen: green and grey on true black. Code content is pure green (hue
-- 120) at three brightnesses; everything secondary is a grey ramp. No white.
-- High-contrast accents appear only to get your attention; syntax itself
-- never uses them:
--   red     errors, diff removals, replace mode, breakpoints
--   orange  warnings, values the debugger saw change
--   yellow  NOTE/TODO in comments, the matching bracket
--   cyan    info diagnostics, hop jump labels, where the debugger is stopped
--
-- Tone map for code:
--   g0        functions, constructors, macros, matches, emphasis
--   g1 bold   keywords, control flow
--   g1        identifiers, variables, properties (main text)
--   g2        strings, numbers, booleans, nullptr
--   gray4     types, namespaces, preprocessor, operators
--   gray3     punctuation, comments (italic)
--   gray2-0   line numbers, borders, whitespace markers

